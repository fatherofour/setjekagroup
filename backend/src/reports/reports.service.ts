import { BadRequestException, ForbiddenException, Injectable, NotFoundException } from '@nestjs/common';
import { randomUUID } from 'node:crypto';
import { existsSync, mkdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PrismaService } from '../prisma/prisma.service.js';
import { ProjectsService } from '../projects/projects.service.js';
import { CommercialService } from '../commercial/commercial.service.js';
import { ProcsaService } from '../delivery/procsa.service.js';
import type { ReportKind } from '../generated/prisma/enums.js';
import { fmtDate, loadReportData } from './report-data.js';
import { progressDeck } from './pptx.js';
import { closeoutPdf, summaryPdf } from './pdf-report.js';
import { workbook } from './xlsx.js';

const KIND: Record<ReportKind, { label: string; ext: string; mime: string; clientFacing: boolean }> = {
  PROGRESS_PPTX: { label: 'Progress report', ext: 'pptx', mime: 'application/vnd.openxmlformats-officedocument.presentationml.presentation', clientFacing: true },
  SUMMARY_PDF: { label: 'Project summary', ext: 'pdf', mime: 'application/pdf', clientFacing: true },
  EXCEL_EXPORT: { label: 'Programme and registers', ext: 'xlsx', mime: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', clientFacing: false },
  CLOSEOUT_PDF: { label: 'Close-out report', ext: 'pdf', mime: 'application/pdf', clientFacing: true },
};

export function reportsDir() {
  const dir = process.env.REPORTS_DIR ?? './uploads/reports';
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  return dir;
}

const SELECT = {
  id: true,
  kind: true,
  title: true,
  periodStart: true,
  periodEnd: true,
  mimeType: true,
  sizeBytes: true,
  clientVisible: true,
  createdAt: true,
  generatedBy: { select: { fullName: true } },
} as const;

/** Reports (Meeting 3 §2.9): the PowerPoint progress report for the client,
 * a PDF summary without tables, the Excel workbook of the programme and
 * registers, and the close-out report. Generated by Setjeka; the client
 * sees the ones Setjeka shares. */
@Injectable()
export class ReportsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly projects: ProjectsService,
    private readonly commercial: CommercialService,
    private readonly procsa: ProcsaService,
  ) {}

  private async access(projectId: string, userId: string) {
    await this.projects.findOneForOwner(projectId, userId);
    const user = await this.prisma.user.findUnique({ where: { id: userId }, select: { role: true, accountType: true } });
    const internal = user?.role === 'ADMIN' || user?.accountType === 'INTERNAL';
    const client = !internal && Boolean(await this.prisma.projectMember.findFirst({ where: { projectId, userId, role: 'CLIENT' } }));
    return { internal, client };
  }

  async list(projectId: string, userId: string) {
    const { internal, client } = await this.access(projectId, userId);
    if (!internal && !client) return [];
    return this.prisma.projectReport.findMany({ where: { projectId, ...(client ? { clientVisible: true } : {}) }, select: SELECT, orderBy: { createdAt: 'desc' } });
  }

  async generate(projectId: string, userId: string, kind: ReportKind, from?: string, to?: string) {
    const { internal } = await this.access(projectId, userId);
    if (!internal) throw new ForbiddenException('Only Setjeka staff generate reports');
    const meta = KIND[kind];
    if (!meta) throw new BadRequestException('Unknown report type');

    const project = await this.prisma.project.findUniqueOrThrow({ where: { id: projectId }, select: { createdAt: true, startDate: true } });
    // Report dates are South African calendar days, whatever the server's zone.
    const end = to ? new Date(`${to}T23:59:59.999+02:00`) : new Date();
    // A weekly report by default, as Setjeka sends today; the close-out
    // covers the whole project.
    const start = from ? new Date(`${from}T00:00:00.000+02:00`) : kind === 'CLOSEOUT_PDF' ? (project.startDate ?? project.createdAt) : new Date(end.getTime() - 7 * 86_400_000);
    if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime()) || start > end) throw new BadRequestException('Choose a valid report period');

    const data = await loadReportData(this.prisma, this.commercial, this.procsa, projectId, userId, { start, end }, { clientFacing: meta.clientFacing });
    const bytes =
      kind === 'PROGRESS_PPTX' ? await progressDeck(data) : kind === 'SUMMARY_PDF' ? await summaryPdf(data) : kind === 'CLOSEOUT_PDF' ? await closeoutPdf(data) : await workbook(data);

    const id = randomUUID();
    const filename = `${id}.${meta.ext}`;
    writeFileSync(join(reportsDir(), filename), bytes);
    return this.prisma.projectReport.create({
      data: {
        id,
        projectId,
        kind,
        title: `${meta.label} · ${fmtDate(start)} – ${fmtDate(end)}`,
        periodStart: start,
        periodEnd: end,
        filename,
        mimeType: meta.mime,
        sizeBytes: bytes.length,
        generatedById: userId,
      },
      select: SELECT,
    });
  }

  async file(projectId: string, userId: string, id: string) {
    const { internal, client } = await this.access(projectId, userId);
    const r = await this.prisma.projectReport.findFirst({ where: { id, projectId }, include: { project: { select: { name: true } } } });
    if (!r || (!internal && !(client && r.clientVisible))) throw new NotFoundException('Report not found');
    const path = join(reportsDir(), r.filename);
    if (!existsSync(path)) throw new NotFoundException('The report file is missing');
    const safeName = `${r.project.name} - ${r.title}`.replace(/[^\w\- ().,]+/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 120);
    return { path, mimeType: r.mimeType, filename: `${safeName}.${KIND[r.kind].ext}` };
  }

  async share(projectId: string, userId: string, id: string, clientVisible: boolean) {
    const { internal } = await this.access(projectId, userId);
    if (!internal) throw new ForbiddenException('Only Setjeka decides what the client sees');
    const r = await this.prisma.projectReport.findFirst({ where: { id, projectId } });
    if (!r) throw new NotFoundException('Report not found');
    return this.prisma.projectReport.update({ where: { id }, data: { clientVisible }, select: SELECT });
  }

  async remove(projectId: string, userId: string, id: string) {
    const { internal } = await this.access(projectId, userId);
    if (!internal) throw new ForbiddenException('Only Setjeka staff remove reports');
    const r = await this.prisma.projectReport.findFirst({ where: { id, projectId } });
    if (!r) throw new NotFoundException('Report not found');
    await this.prisma.projectReport.delete({ where: { id } });
    const path = join(reportsDir(), r.filename);
    try {
      if (existsSync(path)) unlinkSync(path);
    } catch {
      // A leftover file is harmless.
    }
  }
}
